function iconFor(kind = "") {
  const value = kind.toLowerCase();
  if (value.includes("video")) return "Play";
  if (value.includes("blog")) return "Web";
  if (value.includes("drive")) return "Drive";
  if (value.includes("doc")) return "Doc";
  return "PDF";
}

function isExternal(url) {
  return /^https?:\/\//i.test(url) || url.startsWith("mailto:");
}

