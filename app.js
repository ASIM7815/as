function initResourceSearch() {
  const input = document.querySelector("[data-resource-search]");
  if (!input) return;
  const cards = [...document.querySelectorAll(".resource-card")];
  const sections = [...document.querySelectorAll(".resource-section")];
  const empty = document.querySelector("[data-resource-empty]");
  input.addEventListener("input", () => {
    const query = input.value.trim().toLowerCase();
    let shown = 0;
    cards.forEach((card) => {
      const match = card.dataset.resource.includes(query);
      card.style.display = match ? "" : "none";
      if (match) shown += 1;
    });
    sections.forEach((section) => {
      const visible = [...section.querySelectorAll(".resource-card")].some((card) => card.style.display !== "none");
      section.style.display = visible ? "" : "none";
    });
    if (empty) empty.style.display = shown ? "none" : "block";
  });
}

function initReveal() {
  const items = [...document.querySelectorAll(".reveal")];
  if (!items.length) return;
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  items.forEach((item) => observer.observe(item));
}

function initAudioAutoplay() {
  document.querySelectorAll("[data-audio-autoplay]").forEach((video) => {
    video.muted = false;
    video.volume = 1;
    const playAttempt = video.play();
    if (playAttempt && typeof playAttempt.catch === "function") {
      playAttempt.catch(() => {
        video.controls = true;
      });
    }
  });
}

function hydrate() {
  const active = document.body.dataset.page || "";
  renderHeader(active);
  renderFooter();
  renderSubjectCards();
  renderSubjectPage();
  initMenu();
  initNotesFilter();
  initResourceSearch();
  initAudioAutoplay();
  initReveal();
}

document.addEventListener("DOMContentLoaded", hydrate);
